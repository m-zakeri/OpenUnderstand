def test_open_missing_database_raises_understand_error():
    """
    Kept from ``test_case_0``/``test_case_2``.

    The only genuinely novel case Pynguin found: ``api.open()`` on a path that
    is not a file must raise ``UnderstandError`` rather than let a peewee error
    escape.  The manual suite does not cover ``open()`` because it needs an
    on-disk ``.udb``, but the *guard clause* is reachable without one -- which
    is exactly the kind of cheap edge a search-based generator is good at
    spotting.
    """
    with pytest.raises(api.UnderstandError):
        api.open("")


@pytest.mark.parametrize("missing_path", ["", "no_such_file.udb", "."])
def test_open_rejects_any_non_file_path(missing_path):
    """Generalised from the single generated example (empty string only)."""
    with pytest.raises(api.UnderstandError):
        api.open(missing_path)


def test_ref_accessors_tolerate_unpopulated_fields():
    """
    Kept from ``test_case_1``, with assertions added.

    Pynguin built a ``Ref`` from a mix of ``None`` and out-of-range integers --
    a row shape no fixture would produce by hand -- and showed that the scalar
    accessors still return their raw values instead of raising.  Worth pinning:
    ``Ref`` is a dataclass over a database row, and a partially-populated row is
    reachable whenever an analysis pass is interrupted.

    The original called ``ref.line()`` without asserting on it; the assertions
    below are the missing oracle.
    """
    reference = api.Ref(
        _id=None, _kind=-158, _file=-158, _line=None, _column=None,
        _ent=1182, _scope=-158,
    )

    assert reference.line() is None
    assert reference.column() is None
    assert reference.macroexpansion() == ""
    assert reference.isforward() is False
